    List<ParameterType> getParameterTypes() {
        if (parameterMap == null || parameterMap.isEmpty()
                || parameterTypeMap == null || parameterTypeMap.isEmpty()) {
            return Collections.emptyList();
        }
        List<ParameterType> result = new ArrayList<>(parameterMap.size());
        for (Integer parameterIndex : parameterMap.keySet()) {
            result.add(parameterTypeMap.get(parameterIndex));
        }
        return result;
    }

    void setTypedNull(Object parameterIndex, int jdbcType, String typeName)
            throws SQLException {
        if (!JDBCSQLTypeInfo.isSupportedType(jdbcType) && jdbcType != Types.OTHER) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Unsupported_JDBC_type", jdbcType));
        }

        String logicalTypeName = JDBCSQLTypeInfo.normalizeTypeName(typeName);
        if (typeName != null && logicalTypeName == null) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Unsupported_type_name", typeName));
        }
        if (jdbcType == Types.OTHER && logicalTypeName == null) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Type_name_required", jdbcType));
        }
        if (jdbcType == Types.ARRAY && logicalTypeName != null
                && !DataTypeManager.isArrayType(logicalTypeName)) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Array_type_name_required", typeName));
        }
        if (logicalTypeName != null && jdbcType != Types.OTHER
                && !JDBCSQLTypeInfo.isTypeNameCompatible(jdbcType, logicalTypeName)) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Type_name_mismatch", typeName, jdbcType));
        }
        if (logicalTypeName == null && jdbcType != Types.ARRAY) {
            logicalTypeName = JDBCSQLTypeInfo.getTypeName(jdbcType);
        }

        setParameterValue(parameterIndex, null, new ParameterType(jdbcType, logicalTypeName));
    }

    private static int getJdbcType(SQLType sqlType) throws SQLException {
        if (sqlType == null || sqlType.getVendorTypeNumber() == null) {
            throw new KublingSQLException(JDBCPlugin.Util.getString(
                    "MMPreparedStatement.Invalid_SQL_type"));
        }
        return sqlType.getVendorTypeNumber();
    }

    private static String getVendorTypeName(SQLType sqlType) {
        return sqlType instanceof JDBCType ? null : sqlType.getName();
    }

    public ParameterMetaDataImpl getParameterMetaData() throws SQLException {
        if (parameterMetaData == null) {
            //TODO: some of the base implementation of ResultSetMetadata could be on the MetadataProvider
            this.parameterMetaData = new ParameterMetaDataImpl(
                    new ResultSetMetaDataImpl(
                            new MetadataProvider(getMetadataResults().getParameterMetadata()),
                            this.getExecutionProperty(ExecutionProperties.JDBC4COLUMNNAMEANDLABELSEMANTICS)));
        }
        return parameterMetaData;
    }

