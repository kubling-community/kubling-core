    private void setParameterValue(Object parameterIndex, Object value, ParameterType parameterType)
            throws SQLException {
        if (parameterIndex instanceof String s) {
            if (paramsByName == null) {
                paramsByName = new TreeMap<>(String.CASE_INSENSITIVE_ORDER);
                ParameterMetaDataImpl pmdi = getParameterMetaData();
                for (int i = 1; i <= pmdi.getParameterCount(); i++) {
                    String name = pmdi.getParameterName(i);
                    paramsByName.put(name, i);
                }
            }
            parameterIndex = paramsByName.get(s);
            if (parameterIndex == null) {
                throw new KublingSQLException(JDBCPlugin.Util.getString("MMCallableStatement.Param_not_found", s));
            }
        }
        if ((Integer) parameterIndex < 1) {
            throw new KublingSQLException(JDBCPlugin.Util.getString("MMPreparedStatement.Invalid_param_index"));
        }

        if (parameterMap == null) {
            parameterMap = new TreeMap<>();
        }

        if (serverCalendar != null && value instanceof java.util.Date) {
            value = TimestampWithTimezone.create((java.util.Date) value, getDefaultCalendar().getTimeZone(),
                    serverCalendar, value.getClass());
        }
        parameterMap.put((Integer) parameterIndex, value);
        if (parameterType == null) {
            if (parameterTypeMap != null) {
                parameterTypeMap.remove((Integer) parameterIndex);
            }
        } else {
            if (parameterTypeMap == null) {
                parameterTypeMap = new TreeMap<>();
            }
            parameterTypeMap.put((Integer) parameterIndex, parameterType);
        }
    }

